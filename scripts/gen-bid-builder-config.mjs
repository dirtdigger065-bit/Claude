// Generates public/bid-builder/config.js from environment variables so the
// static Bid Builder app (plain JS, not built by Vite) can pick up the same
// Supabase URL/anon key as the React app without hardcoding them in source.
//
// Runs automatically before `npm run dev` / `npm run build` (see package.json).
// Safe to run with nothing configured yet — it just writes empty values and
// the app falls back to read-only public data until you fill in .env.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const rootDir = dirname(dirname(fileURLToPath(import.meta.url)));

function loadDotEnv(path) {
  const vars = {};
  if (!existsSync(path)) return vars;
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    vars[key] = value;
  }
  return vars;
}

const envFromFile = loadDotEnv(join(rootDir, '.env'));
const supabaseUrl = process.env.VITE_SUPABASE_URL || envFromFile.VITE_SUPABASE_URL || '';
const supabaseAnonKey = process.env.VITE_SUPABASE_ANON_KEY || envFromFile.VITE_SUPABASE_ANON_KEY || '';

const out = `// AUTO-GENERATED by scripts/gen-bid-builder-config.mjs — do not edit by hand.
// Regenerated from .env on every "npm run dev" / "npm run build".
window.__RDMPE_CONFIG__ = {
  supabaseUrl: ${JSON.stringify(supabaseUrl)},
  supabaseAnonKey: ${JSON.stringify(supabaseAnonKey)},
};
`;

writeFileSync(join(rootDir, 'public/bid-builder/config.js'), out);

if (!supabaseAnonKey) {
  console.warn(
    '[gen-bid-builder-config] VITE_SUPABASE_ANON_KEY is not set — Bid Builder will be read-only ' +
    '(catalog/bids will load, but saving will fail) until you copy .env.example to .env and fill it in.'
  );
}
